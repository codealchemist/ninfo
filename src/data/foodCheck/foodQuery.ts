function normalize(text: string): string {
  return text
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/\([^)]*\)/g, ' ') // portion notes: "(1 feta)", "(EV, 1 cda sop)"
    .replace(/[^a-z]+/g, ' ')
    .trim()
}

const PHRASE_TOKENS = Object.entries(PHRASES)
  .map(([es, en]) => ({ tokens: es.split(' '), en }))
  .sort((a, b) => b.tokens.length - a.tokens.length)

/** The English search query for a Spanish food name, or null if no word was recognized. */
export function buildFoodQuery(name: string): string | null {
  const tokens = normalize(name).split(' ').filter(Boolean)
  const terms: string[] = []

  for (let i = 0; i < tokens.length; ) {
    const phrase = PHRASE_TOKENS.find(({ tokens: p }) => p.every((t, k) => tokens[i + k] === t))
    if (phrase) {
      terms.push(phrase.en)
      i += phrase.tokens.length
      continue
    }
    const word = WORDS[tokens[i]]
    if (word) terms.push(word)
    i += 1
  }

  const words = Array.from(new Set(terms.join(' ').split(' ')))
  return words.length ? words.join(' ') : null
}
